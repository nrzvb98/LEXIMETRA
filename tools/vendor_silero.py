"""Vendor a minimal Silero VAD checkout into the processing package.

``torch.hub`` normally downloads snakers4/silero-vad from GitHub on first use.
A packaged app cannot depend on that: the first run may be offline, and a
download at that moment fails in front of a user. Bundling a copy makes
``get_model()`` load locally instead (see ``processing/vad.py``).

Only what the JIT path actually needs is copied — ``hubconf.py``, three modules,
and ``silero_vad.jit`` — which is ~2 MB rather than the 35 MB full checkout.
The ONNX variants, datasets, examples, and tuning scripts are all skipped.

    python tools/vendor_silero.py            # check what is vendored
    python tools/vendor_silero.py --apply    # (re-)vendor from the hub cache

The source defaults to torch.hub's cache, which is the checkout the pipeline's
baselines were produced with. Pass --source to use a different one.
"""
from __future__ import annotations

import argparse
import hashlib
import os
import shutil
import sys
from pathlib import Path

APP_ROOT = Path(__file__).resolve().parent.parent
VENDOR_DIR = APP_ROOT / "src" / "hala_rt" / "processing" / "silero"
DEFAULT_SOURCE = Path.home() / ".cache" / "torch" / "hub" / "snakers4_silero-vad_master"

# The JIT path only: hubconf imports silero_vad.utils_vad, model.py pulls in
# init_jit_model, and the weights come from data/silero_vad.jit.
REQUIRED_FILES = [
    "hubconf.py",
    "src/silero_vad/__init__.py",
    "src/silero_vad/model.py",
    "src/silero_vad/utils_vad.py",
    "src/silero_vad/data/silero_vad.jit",
]
OPTIONAL_FILES = ["LICENSE"]


def digest(path: Path) -> str:
    return hashlib.sha256(path.read_bytes()).hexdigest()[:12]


def check() -> int:
    if not VENDOR_DIR.is_dir():
        print(f"No vendored Silero at {VENDOR_DIR}\nRun with --apply.")
        return 1

    missing = [name for name in REQUIRED_FILES if not (VENDOR_DIR / name).is_file()]
    if missing:
        print("Vendored Silero is incomplete:")
        for name in missing:
            print(f"  - missing {name}")
        return 1

    total = sum(f.stat().st_size for f in VENDOR_DIR.rglob("*") if f.is_file())
    print(f"Vendored Silero at {VENDOR_DIR} ({total / 1_048_576:.1f} MB)")
    for name in REQUIRED_FILES:
        print(f"  {digest(VENDOR_DIR / name)}  {name}")
    return 0


def apply(source: Path) -> int:
    if not (source / "hubconf.py").is_file():
        raise SystemExit(
            f"{source} is not a silero-vad checkout (no hubconf.py).\n"
            "Let the pipeline run once to populate torch.hub's cache, or pass "
            "--source PATH."
        )

    missing = [name for name in REQUIRED_FILES if not (source / name).is_file()]
    if missing:
        raise SystemExit(
            f"{source} is missing files this vendoring needs:\n"
            + "\n".join(f"  - {name}" for name in missing)
        )

    if VENDOR_DIR.exists():
        shutil.rmtree(VENDOR_DIR)

    copied = 0
    for name in REQUIRED_FILES + OPTIONAL_FILES:
        origin = source / name
        if not origin.is_file():
            continue
        target = VENDOR_DIR / name
        target.parent.mkdir(parents=True, exist_ok=True)
        shutil.copy2(origin, target)
        copied += 1

    (VENDOR_DIR / "VENDORED.md").write_text(
        "# Vendored Silero VAD\n\n"
        f"Minimal JIT-path copy of snakers4/silero-vad, from `{source}`.\n"
        "Generated by `tools/vendor_silero.py` — do not edit by hand.\n\n"
        "Present so the packaged app loads the model locally instead of "
        "downloading it from GitHub on first run. Only the files the JIT path "
        "needs are here; the ONNX variants, datasets, examples and tuning "
        "scripts are omitted.\n\n"
        "See `LICENSE` for the upstream license.\n"
    )

    total = sum(f.stat().st_size for f in VENDOR_DIR.rglob("*") if f.is_file())
    print(f"Vendored {copied} files ({total / 1_048_576:.1f} MB) into {VENDOR_DIR}")
    print("\nNow run: python -m pytest tests/test_processing_regression.py")
    return 0


def main(argv=None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--apply", action="store_true",
                        help="(Re-)vendor from the source checkout")
    parser.add_argument("--source", default=os.environ.get("SILERO_SOURCE_DIR"),
                        help=f"silero-vad checkout to copy from (default: {DEFAULT_SOURCE})")
    args = parser.parse_args(argv)

    if not args.apply:
        return check()
    return apply(Path(args.source) if args.source else DEFAULT_SOURCE)


if __name__ == "__main__":
    sys.exit(main())
